const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const state = { courses: [], assignments: [], flashcards: [], settings: {} };
const sandbox = { window: {}, AppState: { get: key => state[key] }, document: { getElementById: () => ({}) }, Map, Set };
vm.createContext(sandbox);
vm.runInContext(source.slice(source.indexOf('    class AppOrchestrator'), source.indexOf('    window.NexusApp ='))
    + '\nglobalThis.app = Object.create(AppOrchestrator.prototype);', sandbox);
const app = sandbox.app;
app.tutorialCompletedSteps = new Set();
app.tutorialInitialAnswers = new Map();
app.completeTutorialAction = index => app.tutorialCompletedSteps.add(index);
const check = (index, expected) => {
    app.tutorialStep = index;
    app.checkTutorialProgress();
    assert.equal(app.tutorialCompletedSteps.has(index), expected, app.tutorialSteps()[index].title);
};
check(1, false);
state.courses.push({ code: 'math' });
check(1, true);
check(2, false);
state.assignments.push({ title: 'Homework', courseCode: 'math', dueDate: '2026-10-22' });
check(2, true);
check(3, false);
state.settings.plannerDailyMinutes = 5;
check(3, false);
state.settings.plannerDailyMinutes = 45;
check(3, true);
check(4, false);
app.dashboardSprintAssignmentId = 'homework';
check(4, true);
state.flashcards = [{ id: 'math-deck', cards: [{ id: 'first', front: 'One', back: '1' }] }];
check(5, false);
state.flashcards[0].cards.push({ id: 'second', front: 'Two', back: '2' }, { id: 'third', front: 'Three', back: '3' });
check(5, true);
app.tutorialInitialAnswers.set('math-deck/first', 7);
state.flashcards[0].cards[0].practiceStats = { attempts: 7 };
check(6, false);
state.flashcards[0].cards[0].practiceStats.attempts++;
check(6, true);
check(7, false);
state.settings.startPage = 'planner';
check(7, true);
assert.match(source, /\['state:changed', 'courses:updated', 'assignments:updated', 'flashcards:updated'\]/);
console.log('Tutorial checks saved setup, real deadlines, valid budgets, selected work, three usable cards and a new rated answer; opening controls is not completion.');
